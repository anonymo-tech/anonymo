import assert from 'node:assert/strict';
import { studioReuseDraft } from '../lib/studio-reuse.ts';
const now = Date.now();
const uuid = n => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const verified = { kind: 'video', duration: 5, quality: '720p', aspectRatio: '16:9' };
const route = { versionId: uuid(2), family: 'runway', version: 1, modelId: 'runway-gen4', modality: 'video', expiresAt: new Date(now + 120000).toISOString(), pricing: { maxInputBytes: 50000, variants: [{ options: verified, providerUsd6: '1000000' }] } };
const job = { id: uuid(3), projectId: uuid(1), modelId: route.modelId, modality: 'video', input: { prompt: 'A camera follows the waves.\nKeep the light natural.', privacy: 'standard', options: verified }, billing: { maximumUsd6: '1000000' } };
const exact = studioReuseDraft(job, [route], now);
assert.equal(exact.draft.prompt, job.input.prompt);
assert.deepEqual(exact.draft.modelIds, ['runway']);
assert.equal(exact.draft.duration, '5');
assert.equal(exact.formatChanged, false);
assert.equal('billing' in exact.draft, false);
assert.equal('approval' in exact.draft, false);
assert.equal('quoteId' in exact.draft, false);
assert.equal(studioReuseDraft(job, [{ ...route, expiresAt: new Date(now - 1).toISOString() }], now), null);
assert.equal(studioReuseDraft(job, [], now), null);
const changed = studioReuseDraft({ ...job, input: { ...job.input, options: { ...verified, duration: 10, aspectRatio: '9:16' } } }, [route], now);
assert.equal(changed.formatChanged, true);
assert.equal(changed.draft.duration, '5');
assert.equal(changed.draft.ratio, '16:9');
assert.equal(studioReuseDraft({ ...job, input: { ...job.input, prompt: 'x'.repeat(60000) } }, [route], now), null);
console.log('Studio reuse: 13 current-catalogue, expired-route, full-prompt and fresh-approval checks passed.');
