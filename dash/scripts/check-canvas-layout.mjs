import assert from 'node:assert/strict';
import { canvasLayoutKey, parseCanvasLayout, snapshotCanvasLayout } from '../lib/canvas-layout.ts';
const base = { version: 1, positions: { answer: { x: 500, y: -30 } }, viewport: { x: 10, y: -20, zoom: 0.75 } };
assert.deepEqual(parseCanvasLayout(base), base);
assert.equal(parseCanvasLayout({ ...base, viewport: { ...base.viewport, zoom: NaN } }), null);
assert.equal(parseCanvasLayout({ ...base, viewport: { ...base.viewport, zoom: 2 } }), null);
assert.equal(parseCanvasLayout({ ...base, positions: { answer: { x: Infinity, y: 0 } } }), null);
assert.equal(parseCanvasLayout({ ...base, positions: JSON.parse('{"__proto__":{"x":0,"y":0}}') }), null);
assert.equal(parseCanvasLayout({ ...base, positions: Object.fromEntries(Array.from({ length: 3001 }, (_, i) => [`node-${i}`, { x: 0, y: 0 }])) }), null);
assert.notEqual(canvasLayoutKey('a', 'b:c'), canvasLayoutKey('a:b', 'c'));
assert.notEqual(canvasLayoutKey('account-1', 'project'), canvasLayoutKey('account-2', 'project'));
const saved = snapshotCanvasLayout([{ id: 'answer', position: { x: 12, y: 24 }, data: { secret: 'omit' } }], base.viewport);
assert.deepEqual(saved.positions.answer, { x: 12, y: 24 });
assert.equal(JSON.stringify(saved).includes('secret'), false);
console.log('Canvas layout: 10 validation, account isolation and content-minimization checks passed.');
